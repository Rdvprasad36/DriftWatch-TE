def test_custom_model_provider_registered(monkeypatch: pytest.MonkeyPatch) -> None:
    """Custom provider is built and registered under 'custom' alias."""
    from driftwatch.cli.main import _build_custom_provider_registry

    monkeypatch.setenv("TEST_CUSTOM_API_KEY", "dummy-secret-12345")
    registry = _build_custom_provider_registry(
        base_url="https://api.example.com/v1",
        model_id="test-model-42",
        api_key_env="TEST_CUSTOM_API_KEY",
    )
    assert "custom" in registry
    provider = registry.get("custom")
    assert getattr(provider, "_default_model", None) == "test-model-42"
    assert getattr(provider, "_base_url", None) == "https://api.example.com/v1"


def test_power_simulation_script() -> None:
    """scripts/power_sim.py runs and produces valid power estimates for 3, 5, 10 trials."""
    env = dict(os.environ)
    result = subprocess.run(
        [
            sys.executable,
            "scripts/power_sim.py",
            "--n-simulations",
            "50",
            "--n-scenarios",
            "8",
        ],
        capture_output=True,
        text=True,
        check=True,
        env=env,
    )
    assert "DriftWatch-TE Clustered Power Simulation" in result.stdout
    assert "Trials/Scenario" in result.stdout
    assert "Power" in result.stdout
    # Checks for 3, 5, 10
    lines = result.stdout.splitlines()
    trials_found = [
        line.split()[0] for line in lines if line.strip() and line.split()[0] in ["3", "5", "10"]
    ]
    assert trials_found == ["3", "5", "10"]
