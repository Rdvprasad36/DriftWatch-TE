"""Tests for Phase 2 data layer, weekly reports, custom models, and power simulation.

Covers:
1. Sample data isolation (never in results/, fails if published)
2. Weekly report generator and manifest index
3. Custom model endpoint CLI flags and registry wiring
4. Clustered power simulation script
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest
from click.testing import CliRunner
from tools.make_sample_data import generate_sample_data

from driftwatch.cli.main import cli
from driftwatch.reporting.weekly import generate_weekly_report


def test_sample_data_cannot_target_results(tmp_path: Path) -> None:
    """make_sample_data.py must reject any output path containing 'results'."""
    results_dir = tmp_path / "results" / "summary"
    with pytest.raises(ValueError, match="must NEVER write to results/"):
        generate_sample_data(results_dir)


def test_sample_data_all_contain_sample_flag() -> None:
    """Every JSON file generated by make_sample_data must contain sample: true."""
    sample_dir = Path("dashboard/dev/sample")
    assert sample_dir.is_dir(), "dashboard/dev/sample must exist"

    json_files = list(sample_dir.rglob("*.json"))
    assert len(json_files) >= 4, "Expected at least 4 sample JSON fixtures"

    for jf in json_files:
        data = json.loads(jf.read_text(encoding="utf-8"))
        assert data.get("sample") is True, f"{jf} is missing 'sample': true"


def test_no_sample_data_in_production_results() -> None:
    """Strict guard: No file under results/ may contain 'sample': true."""
    results_dir = Path("results")
    if not results_dir.is_dir():
        return

    for jf in results_dir.rglob("*.json"):
        data = json.loads(jf.read_text(encoding="utf-8"))
        assert data.get("sample") is not True, f"Production file {jf} contains sample: true!"


def test_weekly_report_generation(tmp_path: Path) -> None:
    """generate_weekly_report generates valid markdown and html reports and manifest."""
    out_dir = tmp_path / "reports" / "weekly"
    res = generate_weekly_report(
        week="2026-10-16",
        output_dir=out_dir,
    )

    assert res["report_md"].is_file()
    assert res["report_html"].is_file()
    assert res["manifest"].is_file()

    md_content = res["report_md"].read_text(encoding="utf-8")
    assert "DriftWatch-TE Weekly Report: 2026-10-16" in md_content
    assert "no evidence of change" in md_content
    assert "Pilot" in md_content

    manifest = json.loads(res["manifest"].read_text(encoding="utf-8"))
    assert manifest.get("schema_version") == "1.0.0"
    weeks = [w["week"] for w in manifest.get("weeks", [])]
    assert "2026-10-16" in weeks


def test_weekly_report_cli(tmp_path: Path) -> None:
    """driftwatch weekly-report CLI command executes successfully."""
    runner = CliRunner()
    out_dir = tmp_path / "reports" / "weekly"
    result = runner.invoke(
        cli,
        ["weekly-report", "2026-10-16", "--output-dir", str(out_dir)],
    )
    assert result.exit_code == 0
    assert (out_dir / "2026-10-16.md").is_file()
    assert (out_dir / "2026-10-16.html").is_file()
    assert (out_dir / "index.json").is_file()


